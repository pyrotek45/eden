// Eden DAW — Pixel label helper
//
// Draws strings as 4×5 pixel-block glyphs (no TTF needed).

use sdl2::rect::Rect;
use sdl2::render::Canvas;
use sdl2::video::Window;

use crate::theme::Theme;
use crate::widgets::get_font_scale;

pub fn draw_pixel_label(
    canvas: &mut Canvas<Window>,
    _theme: &Theme,
    text: &str,
    x: i32,
    y: i32,
    max_w: i32,
    color: sdl2::pixels::Color,
) {
    let scale = get_font_scale();
    let gw = 4 * scale;
    let gh = 5 * scale;
    let gap = 1i32;

    canvas.set_draw_color(color);
    let mut cx = x;

    for ch in text.chars() {
        if cx + gw > x + max_w {
            break;
        }
        let rows = glyph_rows(ch);
        for (row, bits) in rows.iter().enumerate() {
            for col in 0..4u8 {
                if bits & (1 << (3 - col)) != 0 {
                    let px = cx + col as i32 * scale;
                    let py = y + row as i32 * scale;
                    if py < y + gh {
                        let _ = canvas.fill_rect(Rect::new(px, py, scale as u32, scale as u32));
                    }
                }
            }
        }
        cx += gw + gap;
    }
}

/// Like `draw_pixel_label` but with a custom pixel scale multiplier.
#[allow(clippy::too_many_arguments)]
pub fn draw_pixel_label_scaled(
    canvas: &mut Canvas<Window>,
    _theme: &Theme,
    text: &str,
    x: i32,
    y: i32,
    max_w: i32,
    color: sdl2::pixels::Color,
    scale: i32,
) {
    let gw = 4 * scale;
    let gap = scale / 2;

    canvas.set_draw_color(color);
    let mut cx = x;

    for ch in text.chars() {
        if cx + gw > x + max_w {
            break;
        }
        let rows = glyph_rows(ch);
        for (row, bits) in rows.iter().enumerate() {
            for col in 0..4u8 {
                if bits & (1 << (3 - col)) != 0 {
                    let px = cx + col as i32 * scale;
                    let py = y + row as i32 * scale;
                    let _ = canvas.fill_rect(Rect::new(px, py, scale as u32, scale as u32));
                }
            }
        }
        cx += gw + gap;
    }
}

